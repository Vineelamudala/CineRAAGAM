// Writes .env.local from the running local Supabase stack (`supabase start`).
// Usage: npm run env:local
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

// Fixed command string (no user input), run through the shell so `npx` resolves on Windows too.
const raw = execSync('npx supabase status -o json', {
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
});
const status = JSON.parse(raw.slice(raw.indexOf('{')));

const url = status.API_URL;
const publishable = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
const secret = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY;
if (!url || !publishable || !secret) {
  console.error('Could not read keys from `supabase status`. Is the stack running?');
  process.exit(1);
}

writeFileSync(
  '.env.local',
  [
    '# Generated by scripts/env-local.mjs for LOCAL development only. Do not commit.',
    `NEXT_PUBLIC_SUPABASE_URL=${url}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}`,
    `SUPABASE_SECRET_KEY=${secret}`,
    '',
  ].join('\n'),
);
console.log(`Wrote .env.local (${url})`);
